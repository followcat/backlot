//! `backlot stage service`: render — or install — a systemd `--user`
//! unit that keeps `backlot stage watch --restart` alive. A user unit
//! runs on this host, so `--remote` is refused; nothing here invokes
//! `systemctl`, the printed commands are what the person runs.

use std::path::{Path, PathBuf};

use crate::args::Common;
use crate::cli::{Env, Fail};

/// The unit file the default unit gets.
pub const UNIT: &str = "backlot-stage.service";

/// `stage service [--print | --write]`: render the unit, or write it
/// under the user's `systemd/user` directory and print how to enable
/// it.
pub(crate) fn run(common: &Common, env: &Env, write: bool) -> Result<String, Fail> {
    let exe = std::env::current_exe()
        .map_err(|e| Fail::refused(format!("cannot find this executable: {e}")))?;
    let session = common.session.as_deref();
    let unit = unit_name(session)?;
    let text = render(&exe, env.get("BACKLOT_STATE_DIR"), session, &unit);
    if !write {
        return Ok(text);
    }
    write_unit(env, &unit, &text)
}

/// Write a rendered systemd user unit under `${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user`
/// and return the install instructions. Never runs `systemctl`.
pub(crate) fn write_unit(env: &Env, unit: &str, text: &str) -> Result<String, Fail> {
    let dir = config_dir(env)?.join("systemd/user");
    std::fs::create_dir_all(&dir)
        .map_err(|e| Fail::refused(format!("cannot create {}: {e}", dir.display())))?;
    let path = dir.join(unit);
    std::fs::write(&path, text)
        .map_err(|e| Fail::refused(format!("cannot write {}: {e}", path.display())))?;
    Ok(format!(
        "wrote {}\nenable it with:\n  systemctl --user daemon-reload\n  systemctl --user enable --now {unit}",
        path.display()
    ))
}

/// Validate a `--session` value against systemd's safe unit-name alphabet.
pub(crate) fn validate_session_name(session: &str) -> Result<(), Fail> {
    let safe = !session.is_empty()
        && session.len() <= 48
        && session
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.'));
    if !safe {
        return Err(Fail::usage(format!(
            "bad --session '{session}': want [A-Za-z0-9_.-]{{1,48}}"
        )));
    }
    Ok(())
}

/// `backlot-stage.service`, or `backlot-stage-<session>.service`.
/// A session name outside systemd's safe unit-name characters is
/// rejected, never mangled into a different unit.
fn unit_name(session: Option<&str>) -> Result<String, Fail> {
    let Some(session) = session else {
        return Ok(UNIT.to_string());
    };
    validate_session_name(session)?;
    Ok(format!("backlot-stage-{session}.service"))
}

/// Shared systemd user unit renderer for both `stage service` and `server service`.
pub(crate) fn render_unit(
    description: &str,
    state_dir: Option<&str>,
    exec_start: &str,
    restart: &str,
    restart_sec: u32,
) -> String {
    let mut environment = Vec::new();
    if let Some(dir) = state_dir {
        environment.push(format!("Environment=\"BACKLOT_STATE_DIR={}\"", escape(dir)));
    }
    let env_block = if environment.is_empty() {
        String::new()
    } else {
        format!("\n{}", environment.join("\n"))
    };
    format!(
        "[Unit]\n\
         Description={description}\n\
         After=default.target\n\
         \n\
         [Service]\n\
         Type=simple\n\
         ExecStart={exec_start}\n\
         Restart={restart}\n\
         RestartSec={restart_sec}{env_block}\n\
         \n\
         [Install]\n\
         WantedBy=default.target\n"
    )
}

/// The unit's exact contents: a comment naming the install command,
/// then the `[Unit]`, `[Service]` and `[Install]` sections.
pub(crate) fn render(
    exe: &Path,
    state_dir: Option<&str>,
    session: Option<&str>,
    unit: &str,
) -> String {
    let exe = exe.to_string_lossy();
    let mut exec = format!("{} stage watch --restart", quote(&exe));
    if let Some(session) = session {
        exec.push_str(&format!(" --session {}", quote(session)));
    }
    let exe_dir = exe
        .rsplit_once('/')
        .map(|(dir, _)| dir)
        .filter(|dir| !dir.is_empty())
        .unwrap_or("/");
    let mut environment = vec![format!(
        "Environment=\"PATH={}\"",
        escape(&format!("{exe_dir}:/usr/local/bin:/usr/bin:/bin"))
    )];
    if let Some(state_dir) = state_dir {
        environment.push(format!(
            "Environment=\"BACKLOT_STATE_DIR={}\"",
            escape(state_dir)
        ));
    }
    format!(
        "# Backlot stage supervisor, generated by `backlot stage service`.\n\
         # Install it with:\n\
         #   systemctl --user daemon-reload && systemctl --user enable --now {unit}\n\
         \n\
         [Unit]\n\
         Description=Backlot stage supervisor (keeps the stage alive and reconnects the hc core)\n\
         After=default.target\n\
         \n\
         [Service]\n\
         Type=simple\n\
         ExecStart={exec}\n\
         Restart=on-failure\n\
         RestartSec=5\n\
         {environment}\n\
         \n\
         [Install]\n\
         WantedBy=default.target\n",
        environment = environment.join("\n"),
    )
}

/// One `ExecStart` word: quoted and escaped when it holds anything
/// systemd's unquoted form does not take.
pub(crate) fn quote(word: &str) -> String {
    let plain = !word.is_empty()
        && word
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "_-/.:@+".contains(c));
    if plain {
        word.to_string()
    } else {
        format!("\"{}\"", escape(word))
    }
}

/// systemd's double-quote escaping: a backslash and a double quote.
fn escape(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// `${XDG_CONFIG_HOME:-$HOME/.config}` from the passed environment.
fn config_dir(env: &Env) -> Result<PathBuf, Fail> {
    if let Some(dir) = env.get("XDG_CONFIG_HOME").filter(|d| !d.is_empty()) {
        return Ok(PathBuf::from(dir));
    }
    let home = env
        .get("HOME")
        .filter(|h| !h.is_empty())
        .ok_or_else(|| Fail::refused("neither XDG_CONFIG_HOME nor HOME is set"))?;
    Ok(PathBuf::from(home).join(".config"))
}

