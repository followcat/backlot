# Neutral fixture repository, cast and input files for run-smoke.sh.
# Sourced; the caller owns REPO, INPUTS, ROOT, RUNNER, MODEL and EFFORT.

make_repo() {
    mkdir -p "$REPO/src" "$REPO/tests"
    git -C "$REPO" init -q -b main
    cat >"$REPO/src/shop.py" <<'EOF'
def total(prices):
    return sum(prices)
EOF
    cat >"$REPO/tests/test_shop.py" <<'EOF'
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from shop import total


class ShopTest(unittest.TestCase):
    def test_total(self):
        self.assertEqual(total([1, 2, 3]), 6)


if __name__ == "__main__":
    unittest.main()
EOF
    printf '# acme-shop\n\nNeutral smoke fixture.\n' >"$REPO/README.md"
    git -C "$REPO" add README.md src/shop.py tests/test_shop.py
    git -C "$REPO" -c user.name=alice -c user.email=alice@example.com \
        commit -q -m "init acme-shop"
}

cast_identity() { # role model profile
    printf '\n[%s]\nrunner = "%s"\nmodel = "%s"\n' "$1" "$RUNNER" "$2"
    if [ -n "$EFFORT" ]; then printf 'effort = "%s"\n' "$EFFORT"; fi
    printf 'permission_profile = "%s"\n' "$3"
}

write_cast() {
    {
        cat <<'EOF'
# Generated by scripts/smoke/run-smoke.sh — neutral values only.
rework_cap = 2
stall_limit_s = 60
nudge_after_s = 30
escalate_after_s = 120
design_gate = "off"

[limits]
# 3 seats the fixed pair and either the writer or one actor.
EOF
        printf '%s = 3\n' "$RUNNER"
        cast_identity producer "$MODEL" standard
        cast_identity director "$MODEL" standard
        cast_identity writer "$MODEL" standard
        printf '\n[[candidates]]\nname = "actor-a"\n'
        printf 'runner = "%s"\nmodel = "%s"\n' "$RUNNER" "$MODEL"
        if [ -n "$EFFORT" ]; then printf 'effort = "%s"\n' "$EFFORT"; fi
        printf 'permission_profile = "worktree"\n'
    } >"$ROOT/cast.toml"
}

write_inputs() {
    printf '# requirement\n\nOne small task for the smoke run.\n' >"$INPUTS/req.md"
    printf '# plan\n\n1. Return the sum of a list of prices.\n' >"$INPUTS/plan.md"
    printf '# acceptance\n\n- `total([1, 2, 3])` returns 6.\n' >"$INPUTS/acc.md"
    printf 'director: one task, then stop.\n' >"$INPUTS/note.md"
    printf '# delivery report\n\nSmoke delivery.\n' >"$INPUTS/report.md"
}
